#!/usr/bin/env bash
# Measure / , work out how much must move to bring it to the target %, pick the biggest
# home folders until that amount is covered, and write the move commands to do_move.sh.
# This script itself changes NOTHING - it only measures and writes do_move.sh for you to review.
set -u
TARGET=${1:-50}                      # target Use% (default 50)
DEST=/mnt/data/pan/home
OUT="$(dirname "$(readlink -f "$0")")/do_move.sh"

read -r _ size used avail _ < <(df -B1 --output=source,size,used,avail,pcent / | tail -1)
total=$((used + avail))              # df's Use% is used / (used + avail)
need=$(( used - total * TARGET / 100 ))
h() { numfmt --to=iec "$1"; }

echo "Root (/): used $(h $used) of $(h $total) -> $((100*used/total))%"
echo "Target ${TARGET}%: need to move about $(h $need)"
echo "Free on /mnt/data: $(h "$(df -B1 --output=avail /mnt/data | tail -1)")"
echo
echo "Measuring every folder in your home (1-3 minutes)..."

# every top-level item in home, except things that must stay or are tiny/system-linked
mapfile -t LIST < <(
  find "$HOME" -mindepth 1 -maxdepth 1 -type d ! -name snap ! -name .config ! -name .local \
       ! -name .ssh ! -name .gnupg ! -name .pki ! -name Desktop ! -name .var -print0 |
  xargs -0 -r du -sxB1 2>/dev/null | sort -rn
)

echo
echo "== Biggest folders in home =="
for line in "${LIST[@]:0:20}"; do
  printf "  %7s  %s\n" "$(h "${line%%$'\t'*}")" "${line#*$'\t'}"
done

# greedy: take the biggest until we reach the amount needed
picked=(); sum=0
for line in "${LIST[@]}"; do
  (( sum >= need )) && break
  b=${line%%$'\t'*}; (( b < 200*1024*1024 )) && continue   # skip <200MB, not worth it
  picked+=("${line#*$'\t'}"); sum=$((sum + b))
done

echo
echo "== Plan: move these (total $(h $sum)) =="
for p in "${picked[@]}"; do echo "  $p"; done
after=$(( 100 * (used - sum) / total ))
echo "Expected / after move: about ${after}%"
(( sum < need )) && echo "NOTE: home folders alone are not enough - paste this output to Claude."

# write the move script
{
  echo '#!/usr/bin/env bash'
  echo '# Generated by plan_move.sh - close VS Code, Jupyter, Vivado, STM32CubeIDE, conda terminals first.'
  echo 'set -u'
  echo "DEST=$DEST"
  echo 'sudo mkdir -p "$DEST" && sudo chown "$USER:$USER" /mnt/data/pan "$DEST"'
  echo 'mv1() { p=$1; n=$(basename "$p"); [[ -L $p ]] && { echo "skip $p (already a link)"; return; }'
  echo '  [[ -e $DEST/$n ]] && { echo "skip $p ($DEST/$n exists)"; return; }'
  echo '  echo ">> $p"; if rsync -aHAX --info=progress2 "$p/" "$DEST/$n/"; then rm -rf "$p" && ln -s "$DEST/$n" "$p" && echo "   ok"; else echo "   copy FAILED, original kept"; rm -rf "${DEST:?}/$n"; fi; }'
  for p in "${picked[@]}"; do printf 'mv1 %q\n' "$p"; done
  echo 'df -h /'
} > "$OUT"
chmod +x "$OUT"
echo
echo "Move commands written to: $OUT"
echo "Review it (cat \"$OUT\"), then run:  bash \"$OUT\""
